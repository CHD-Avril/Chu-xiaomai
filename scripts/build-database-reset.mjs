// Generates a single SQL Editor script from the tested migrations.
// This script only writes a local file. It does not connect to or reset any database.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

const root = new URL("../", import.meta.url);
export const sourceFiles = ["supabase-schema.sql", "supabase-admin-workflow.sql", "supabase-database-integrity.sql", "supabase-test-mode.sql"];
const resetTables = ["song_reports", "song_dislikes", "song_likes", "broadcast_playlists", "songs", "announcements", "vote_attempts", "api_request_attempts", "playlist_periods", "admin_action_log", "database_repair_archive", "security_settings", "test_accounts"];

export function buildResetSql() {
  const sources = sourceFiles.map(name => ({ name, sql: readFileSync(new URL(name, root), "utf8").replace(/^\uFEFF/, "").replace(/\r\n/g, "\n") }));
  // Keep the admin identity helpers because existing admin_users policies reference them.
  // Remove every overload of the other application functions, including legacy report endpoints.
  const helperNames = new Set(["is_current_user_admin", "is_admin_email_allowed"]);
  const functionNames = [...new Set(sources.flatMap(({ sql }) => [...sql.matchAll(/^create (?:or replace )?function public\.([a-z_]+)\s*\(/gm)].map(match => match[1])))].filter(name => !helperNames.has(name));
  functionNames.push("report_song");
  const sections = sources.map(({ name, sql }) => {
    if ((sql.match(/^begin;\s*$/gm) ?? []).length !== 1 || (sql.match(/^commit;\s*$/gm) ?? []).length !== 1) throw new Error(`${name}: expected one top-level transaction`);
    return `-- ===== ${name} =====\n` + sql.replace(/^begin;\s*$/m, "").replace(/^commit;\s*$/m, "").trim();
  });
  return `-- GENERATED by node scripts/build-database-reset.mjs. Do not edit this file directly.
-- Revision: nonblocking maintenance locks before any changes; conflict repair uses one CTE.
-- WARNING: running this SQL permanently clears this app's existing business data.
-- Deletes songs, votes, reports, periods, announcements, broadcast playlists, logs,
-- security settings and test-account grants, then rebuilds the latest schema and permissions.
-- Preserves auth.users (login accounts), public.admin_users (admin authorization),
-- Storage and unrelated tables. Existing test accounts need to be authorized again.
-- Run the ENTIRE file once in Supabase SQL Editor during a maintenance window.
-- Close app tabs and other database queries first. Busy tables abort safely before deletion.
-- One transaction: any error rolls back both the deletion and the rebuild.
-- This is a reset, NOT an incremental migration. Running it again clears new data too.

begin;
set local lock_timeout = '500ms';

-- Acquire the strongest required locks before changing anything. NOWAIT prevents
-- waiting on a reader that might itself need another table held by this reset.
-- Auth accounts are preserved; their lock only pauses writes during FK rebuilding.
do $maintenance_locks$
declare item record;
begin
  if not pg_try_advisory_xact_lock(hashtextextended('chu:reset-and-rebuild',0)) then
    raise exception '已有数据库重建任务正在执行，请等待其结束后再操作。' using errcode='55P03';
  end if;
  for item in
    select * from (values
      ('auth.users','SHARE ROW EXCLUSIVE'),
      ${[...resetTables, "admin_users"].sort().map(name => `('public.${name}','ACCESS EXCLUSIVE')`).join(",\n      ")}
    ) as targets(relation_name,lock_mode) order by relation_name
  loop
    if to_regclass(item.relation_name) is not null then
      begin
        execute format('lock table %s in %s mode nowait',item.relation_name,item.lock_mode);
      exception when lock_not_available then
        raise exception '重建已安全停止：表 % 正被其他会话使用，尚未删除业务数据。',item.relation_name
          using errcode='55P03',hint='关闭用户端、运营台、Supabase Table Editor 及其他正在运行的 SQL；结束未提交事务后，再完整运行本文件一次。';
      end;
    end if;
  end loop;
end;
$maintenance_locks$;

-- Drop only the named business tables together. No CASCADE: unknown external
-- dependencies stop the reset instead of deleting unrelated objects.
drop table if exists ${resetTables.map(name => "public." + name).join(",\n  ")};

do $remove_app_functions$
declare item record;
begin
  for item in select p.oid,p.proname,pg_get_function_identity_arguments(p.oid) args
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace
    where n.nspname='public' and p.prokind='f' and p.proname=any(array[${functionNames.map(name => "'" + name + "'").join(",")}])
  loop
    execute format('drop function public.%I(%s)',item.proname,item.args);
  end loop;
end;
$remove_app_functions$;

${sections.join("\n\n")}

notify pgrst, 'reload schema';
commit;

-- Empty business tables are expected. Open the operations desk to create a new period.
select '重建完成：业务数据已清空，登录账号和管理员名单已保留。请刷新运营台，新建征集期并重新授权测试账号。' as result;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const sql = buildResetSql();
  writeFileSync(new URL("supabase-reset-and-rebuild.sql", root), sql, "utf8");
  process.stdout.write(`Generated supabase-reset-and-rebuild.sql (${sql.split("\n").length} lines)\n`);
}
